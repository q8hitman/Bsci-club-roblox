import re

p = "kuwait-parkour/src/server/Questions.luau"
s = open(p, encoding="utf-8").read()
head, body = s.split("return {\n", 1)
blocks = re.split(r"(?m)^\t\{ name = ", body)
banks = {}
for b in blocks[1:]:
    name = re.match(r'"([^"]+)"', b).group(1)
    banks["\t{ name = " + b.rstrip().rstrip("}").rstrip() if False else name] = "\t{ name = " + b.split("\n} ", 1)[0] if False else None
# simpler: re-extract each bank text up to its closing "} },"
banks = {}
for m in re.finditer(r'(?ms)^\t\{ name = "([^"]+)", items = \{\n(.*?)^\t\} \},', body):
    banks[m.group(1)] = m.group(2)

zoology = '''		{ "أي مما يلي من الزواحف؟", "السحلية", "الدلفين", "النسر" },
		{ "الحيوانات التي تلد وترضع صغارها تسمى؟", "الثدييات", "الزواحف", "الحشرات" },
		{ "كم عدد أرجل الحشرة؟", "6", "4", "8" },
		{ "أي حيوان يعيش في الماء ويتنفس بالخياشيم؟", "السمكة", "القطة", "الحصان" },
		{ "أي حيوان من الطيور التي لا تطير؟", "النعامة", "الحمامة", "الصقر" },
		{ "تمرّ الضفدعة في مرحلة صغيرة تسمى؟", "الشرغوف", "اليرقة", "البيضة" },
'''
physiology = '''		{ "أي عضو يضخ الدم في الجسم؟", "القلب", "الكبد", "الرئة" },
		{ "أي عضو مسؤول عن التنفس؟", "الرئتان", "المعدة", "الكليتان" },
		{ "أين يحدث معظم امتصاص الغذاء؟", "الأمعاء الدقيقة", "المعدة", "الفم" },
		{ "الخلايا التي تنقل الأكسجين في الدم؟", "خلايا الدم الحمراء", "خلايا الدم البيضاء", "الصفائح" },
		{ "أي عضو يتحكم في أفعال الجسم والتفكير؟", "الدماغ", "الكبد", "الطحال" },
		{ "الجهاز الذي يحمي الجسم من الأمراض؟", "الجهاز المناعي", "الجهاز الهضمي", "الجهاز الهيكلي" },
'''
banks["علم الحيوان"] = zoology
banks["الفسيولوجيا"] = physiology

order = [
    ("علم النبات", "علم النبات"),
    ("علم الحيوان", "علم الحيوان"),
    ("الأحياء الدقيقة", "الأحياء الدقيقة"),
    ("بيولوجيا الخلية", "بيولوجيا الخلية"),
    ("علم الوراثة", "علم الوراثة"),
    ("الكيمياء الحيوية", "الكيمياء الحيوية"),
    ("علم البيئة", "علم البيئة"),
    ("الفسيولوجيا", "الفسيولوجيا"),
    ("التقنية الحيوية", "التقنية الحيوية"),
    ("المعلوماتية الحيوية", "المعلوماتية الحيوية"),
]
out = [head + "return {\n"]
for key, title in order:
    out.append('\t{ name = "%s", items = {\n%s\t} },\n' % (title, banks[key]))
out.append("}\n")
open(p, "w", encoding="utf-8").write("".join(out))
print("banks:", [k for k, _ in order])
